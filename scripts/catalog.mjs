import { readFile, writeFile } from 'node:fs/promises';
import { format } from 'prettier';
import { z } from 'zod';
import { buildTools } from '../dist/tools.js';
import { loadConfig } from '../dist/config.js';

const tools = buildTools(loadConfig({ ALTEGIO_PARTNER_TOKEN: 'catalog-synthetic' })).sort((a, b) =>
  a.name.localeCompare(b.name)
);
const inventory = tools.map((tool) => ({
  name: tool.name,
  description: tool.description,
  readOnly: tool.readOnly,
  destructive: tool.destructive,
  inputSchema: z.toJSONSchema(tool.schema),
  ...(tool.outputSchema ? { outputSchema: z.toJSONSchema(tool.outputSchema) } : {}),
}));
const markdown =
  `# Tool inventory\n\nGenerated by \`npm run catalog\`; do not edit by hand.\n\n${tools.length} tools. API classifications and authorization requirements are in [tool-boundaries.md](tool-boundaries.md). Moderation submission is an owner action; moderation decisions and backoffice tools are excluded.\n\n| Tool | Read only | Destructive hint | Description |\n| --- | --- | --- | --- |\n` +
  tools
    .map(
      (tool) =>
        `| \`${tool.name}\` | ${tool.readOnly ? 'yes' : 'no'} | ${tool.destructive ? 'yes' : 'no'} | ${tool.description.replaceAll('|', '\\|')} |`
    )
    .join('\n') +
  '\n';
for (const [path, content, parser] of [
  ['docs/tools.json', JSON.stringify(inventory), 'json'],
  ['docs/tools.md', markdown, 'markdown'],
]) {
  const rendered = await format(content, { parser, printWidth: 100 });
  if (process.argv.includes('--check')) {
    if ((await readFile(path, 'utf8')) !== rendered)
      throw new Error(`${path} is stale; run npm run catalog`);
  } else await writeFile(path, rendered);
}
console.log(`Tool inventory verified: ${tools.length} tools`);
